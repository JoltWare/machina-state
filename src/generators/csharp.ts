// C# code generator.
//
// Turns an analysed Machine (see src/model.ts) into a single C# source file containing one
// `public abstract class` named after the diagram. The user derives from that class and implements the
// guard and action hooks as `protected override` methods; the generated code owns the active state
// configuration and implements the full statechart semantics described in the "Execution Semantics"
// chapter of docs/manual.tex. The reference interpreter in src/engine.ts implements the same semantics,
// and the test suite checks that the simulator and every generated variant produce identical traces, so
// the structure of the emitted methods deliberately mirrors the engine (and the C++ generator in cpp.ts)
// method for method: DispatchState, HandleEvent, ExitState, EnterDown, EnterState, EnterDefault,
// EnterHistory, EnterRegion, RunCompletions, MarkCompletion, ... Golden copies of the output live in
// test/golden/*.cs.
//
// Shape of the emitted class (members in brackets depend on the diagram or the codegen options):
//
//     // <auto-generated> ... </auto-generated>
//     #nullable enable
//     using System; [using System.Collections.Generic;]
//     [namespace Ns {]
//     public abstract class Name
//     {
//         public enum State { A, B, // in A ... , None }        // pre-order; None is last
//         public enum Event { ..., [X_After500ms,] [Completion] }
//         [public enum TraceKind { Start, Event, Ignored, Transition, Exit, Enter }]
//         public const int StateCount, RegionCount; [QueueCapacity]
//         [table: TransitionRow class, static structure arrays, delegate arrays]
//         private readonly State[] active;              // one slot per region; region 0 = top level
//         [history (state last exited per region), exited, pending completion flags,
//          timer generations/armed flags, Queue<Func<bool>>, event-argument fields]
//         [table: protected Name() building the delegate arrays and the transition table]
//         public State Current; public bool IsFinished;  // properties
//         public void Start(); public bool Dispatch(Event); [DispatchX(args...)]; [DispatchTimeout(...)]
//         public bool IsIn(State); public static State ParentOf(State);
//         [protected abstract Lock()/Unlock()] [protected abstract StartTimer()/CancelTimer()]
//         [protected virtual Trace()] [protected Post()/PostX()]
//         protected abstract bool guard(...); protected abstract void action(...);
//         private DispatchCore, DispatchState, [DrainQueue], [Fire_n], [RunCompletions, MarkCompletion, ...],
//         [StartTimers, CancelTimers, TimerIndex], HandleEvent, RegionOf/FirstRegionOf/RegionsOf,
//         EnterRegion, [OnEntry/OnExit (switch)], [IsDeepHistory (switch)], ExitState, EnterDown,
//         EnterState, EnterDefault, [EnterHistory], Innermost
//     }
//
// Runtime representation. The active configuration is an array with one slot per region (regions of one
// state have consecutive indices, see MRegion.index); a slot holds the active state of that region or
// State.None. Because every state lives in exactly one region, `active[RegionOf(s)] == s` means "s is
// active", for leaves and composites alike. States are numbered in pre-order, so `(int)state` equals
// MState.index and can index per-state arrays (`pending` and the table-style arrays). With history
// pseudostates, `history` holds the state last exited from each region (indexed like `active`); a composite is
// always exited with its whole active subtree, so these slots describe the configuration below every composite
// at its last exit, which EnterHistory restores.
//
// Styles (same public interface, identical behaviour):
//   * 'switch' - structure and behaviour are compiled into control flow: ParentOf/RegionOf/... are
//     switch expressions, HandleEvent is a nested `switch (state) { switch (trigger) }` with the guards,
//     exits, actions and entries of every transition written out (the exit root and least common
//     ancestor are resolved at generation time), and OnEntry/OnExit/EnterRegion are switch statements.
//   * 'table'  - structure lives in static readonly arrays indexed by `(int)state` or region index, the
//     hooks in instance arrays of `Action?` delegates, and the transitions in a TransitionRow[] table that
//     HandleEvent scans linearly; TryRow interprets one row (computing the exit root at run time). The
//     delegate arrays and the table reference instance methods, so they are built in the protected
//     constructor rather than as static initialisers.
//
// Options (Machine flags set from the diagram's codegen settings):
//   * trace      - adds the TraceKind enumeration, an empty `protected virtual Trace` hook, and Trace calls
//                  for start, every dispatched/ignored event, every transition (before any exit), every
//                  exit (before exit actions) and every entry (before entry actions).
//   * threadSafe - adds abstract Lock/Unlock hooks; every public member (properties included) wraps its
//                  body in Lock(); try { ... } finally { Unlock(); }. Post is deliberately not locked: it
//                  is meant to be called from hooks, which already run under the lock.
//   * queue      - adds a Queue<Func<bool>> bounded to QueueCapacity entries (Post returns false when it is
//                  full) and protected Post/PostX methods; each public entry point (Start, Dispatch*,
//                  DispatchTimeout) drains the queue after its own event (and its completions) has been
//                  processed, before returning.
//
// Differences from the C++ generator (cpp.ts), whose helpers completionOwner and exitRoot are reused:
//   * Allman braces (`new Writer(true)`), `public abstract class`, `#nullable enable`, `protected abstract`
//     hooks instead of pure virtual functions, `protected virtual Trace` instead of a virtual no-op.
//   * Event arguments are copied into private fields named `<Event>_<param>` before dispatch, instead of
//     C++'s pointer to a stack-allocated argument struct (`ArgsOfX()`); the fields keep their last value.
//   * Locking uses try/finally instead of an RAII ScopedLock; read-only accessors are properties
//     (Current, IsFinished) rather than const member functions.
//   * The event queue stores closures (`Func<bool>`) that set the argument fields and call DispatchCore,
//     instead of a ring buffer of QueuedEvent structs; it is bounded by the same capacity setting.
//   * Table-style hooks are delegates (method groups or lambdas) instead of member-function pointers.
//   * No StateName/EventName helpers are generated: C# enums already have ToString(), which is also what
//     the trace calls use.
//   * Namespaces written C++-style with `::` are converted to C#'s dotted form.
// The emitted code uses Array.Fill, so it needs .NET Core 2.0 / .NET Standard 2.1 or later.

import { alwaysFires, COMPLETION_EVENT, isExhaustive, Machine, MBranch, MState, MTransition, Style } from '../model';
import { completionOwner, exitRoot } from './cpp';
import { Writer } from './writer';

/**
 * Generates the C# implementation of a state machine.
 *
 * The machine must already have been analysed without errors (parent links, regions, least common
 * ancestors, timers and completion information are taken as given). The function is a straight-line
 * emitter: it writes the members of the class in their final order, choosing between the switch and
 * table variants of each member as it goes.
 *
 * @param m Analysed machine (from src/model.ts) including its codegen options (trace, threadSafe, queue).
 * @param style 'switch' for control-flow based code, 'table' for data-driven code (see the file overview).
 * @returns The complete C# source text, ending with a newline.
 */
export function generateCSharp(m: Machine, style: Style): string {
    const w = new Writer(true);
    const cls = m.name;
    const table = style === 'table';
    // C# expressions for a state (null/undefined = the top level, State.None) and for an event.
    const st = (s: MState | null | undefined) => `State.${s ? s.name : 'None'}`;
    const ev = (e: string) => `Event.${e}`;
    // Final states directly in the top-level region: reaching one of them finishes the machine.
    const topFinals = m.states.filter(s => s.isFinal && !s.parent);
    // Events that carry parameters; they get typed DispatchX/PostX methods and argument fields.
    const paramEvents = m.events.filter(e => (m.params.get(e) ?? []).length > 0);
    const hasArgs = paramEvents.length > 0;
    const historyStates = m.states.filter(s => s.history);
    const hasHistory = historyStates.length > 0;
    const hasInternal = m.transitions.some(t => t.internal);
    // Transitions that lead into a choice point; each one gets its own Fire_n method.
    const compound = m.transitions.filter(t => t.branches);
    const hasTimers = m.timers.length > 0;
    // True if any state has more than one region; only then is the code for filling in sibling regions
    // (EnterDown) and, in switch style, IsFinalState needed.
    const orthogonal = m.states.some(s => s.regions.length > 1);
    // Stateflow semantics (see model.ts): outer-first DispatchState, during actions and step counters. All
    // output for UML diagrams is unaffected by these flags.
    const stateflow = m.semantics === 'stateflow';
    const hasDuring = m.states.some(s => s.during.length > 0);
    const temporal = m.temporal;
    // Condition under which transition `t` is tried: its step counter (temporal transitions, tested first)
    // and its guard, or '' when it has neither.
    const condition = (t: MTransition, e: string) =>
        [...(t.ticks !== undefined ? [`ticks[${t.source.index}] >= ${t.ticks}u`] : []), ...(t.guard ? [guardCall(t, e)] : [])].join(' && ');
    // Events that the untyped Dispatch(Event) and Post(Event) refuse: events with parameters (their
    // arguments would be missing) and the internal Completion pseudo-event, which only RunCompletions
    // may deliver. Timeout events are not in this list: Dispatch(timeout) is allowed but bypasses the
    // stale-timer check of DispatchTimeout.
    const rejected = [...paramEvents, ...(m.completion ? [COMPLETION_EVENT] : [])];

    // Parameter declarations of a guard/action hook ("int cents"), for its abstract declaration.
    const paramDecls = (hook: string) => (m.hookParams.get(hook) ?? []).map(p => p.decl).join(', ');
    // Name of the private field that holds parameter `name` of event `e` while it is being dispatched.
    const argField = (e: string, name: string) => `${e}_${name}`;
    // Argument list passing the stored parameters of event `e` to a hook ('' for parameterless events).
    const callArgs = (e: string) => (m.params.get(e) ?? []).map(p => argField(e, p.name)).join(', ');
    // Call expression of a hook; transition hooks receive the event's parameters, entry/exit/initial
    // actions (no `e`) never do.
    const call = (hook: string, e?: string) => `${hook}(${e ? callArgs(e) : ''})`;
    // Guard test of a transition or branch, honouring `!guard` negation.
    const guardCall = (t: { guard?: { name: string; negate: boolean } }, e: string) => `${t.guard!.negate ? '!' : ''}${call(t.guard!.name, e)}`;
    // Quoted trace name of a transition: "S -> T", "S -> T (history)" or "S (internal)".
    const transitionName = (t: MTransition) =>
        `"${t.source.name}${t.internal ? ' (internal)' : ` -> ${t.target.name}${t.history ? ' (history)' : ''}`}"`;
    // Name of the method that performs a choice-point transition; the index into m.transitions keeps it
    // unique even when several transitions share a choice point (each is resolved per source state).
    const fireName = (t: MTransition) => `Fire_${m.transitions.indexOf(t)}`;
    // Call of EnterDown; its third parameter (enter the target through its history pseudostate) only exists
    // when the diagram has history pseudostates.
    const enterDown = (from: string, target: string, history: string) => `EnterDown(${from}, ${target}${hasHistory ? `, ${history}` : ''})`;

    /**
     * C# expression of type `Action?` that runs a list of hooks, for the table-style delegate arrays.
     * Uses `null` for no hooks and a bare method group for a single parameterless hook (cheapest, and
     * readable in the table); otherwise a lambda that calls the hooks in order, passing the stored
     * arguments of event `e` when it has any.
     */
    const delegate = (actions: string[], e?: string): string => {
        if (actions.length === 0) {
            return 'null';
        }
        if (actions.length === 1 && !(e && callArgs(e))) {
            return actions[0];
        }
        return `() => { ${actions.map(a => `${call(a, e)};`).join(' ')} }`;
    };
    /**
     * Emits a `switch` statement over `subject`. Each case's lines are written verbatim, so callers must
     * end them with `break;` or `return` (C# forbids falling through to the next case). Emits nothing at
     * all when there are no cases, leaving e.g. an empty OnEntry body.
     */
    const switchOn = (subject: string, cases: { labels: string[]; lines: string[] }[]) => {
        if (cases.length === 0) {
            return;
        }
        w.open(`switch (${subject})`);
        for (const c of cases) {
            c.labels.forEach(l => w.line(`case ${l}:`));
            w.indent();
            c.lines.forEach(l => w.line(l));
            w.dedent();
        }
        w.close();
    };
    /** Emits a block-bodied member with the given signature, followed by a blank separator line. */
    const method = (signature: string, body: () => void) => {
        w.open(signature);
        body();
        w.close();
        w.line('');
    };
    // Expression-bodied mapping from states to a value, as a switch expression.
    // Arms with an empty state list are dropped; when no arm remains the member collapses to
    // `signature => fallback;`. The `_ =>` arm covers every other state, including State.None.
    const stateMap = (signature: string, arms: [MState[], string][], fallback: string) => {
        const used = arms.filter(([list]) => list.length > 0);
        if (used.length === 0) {
            w.line(`${signature} => ${fallback};`);
            w.line('');
            return;
        }
        w.line(`${signature} => state switch`);
        w.line('{');
        w.indent();
        used.forEach(([list, value]) => list.forEach(s => w.line(`${st(s)} => ${value},`)));
        w.line(`_ => ${fallback},`);
        w.dedent();
        w.line('};');
        w.line('');
    };

    // ---- File header, usings and namespace ----
    // The <auto-generated> marker makes analysers and IDEs treat the file as generated code.
    w.line('// <auto-generated>');
    w.line(`//     ${cls}: ${style}-based hierarchical state machine generated by MachinaState.`);
    w.line('//     Do not edit by hand. Derive from this class and implement the guard and action hooks.');
    if (stateflow) {
        w.line(`//     Stateflow semantics: call Dispatch(Event.${m.stepEvent}) once per step; outer states see every event first.`);
    }
    w.line('// </auto-generated>');
    w.line('#nullable enable');
    w.line('using System;');
    // Queue<T> is the only collection type used, and only with the event queue option.
    if (m.queue) {
        w.line('using System.Collections.Generic;');
    }
    w.line('');
    // Diagram namespaces may be written C++-style (`A::B`); C# needs `A.B`.
    if (m.namespace) {
        w.open(`namespace ${m.namespace.replace(/::/g, '.')}`);
    }

    // ---- Public enumerations and constants ----
    w.open(`public abstract class ${cls}`);
    // States in pre-order, so `(int)state` equals MState.index; None comes last, so it equals StateCount
    // and is not a valid index into the per-state arrays (accessors guard against it where needed).
    w.open('public enum State');
    for (const s of m.states) {
        w.line(`${s.name},${s.parent ? ` // in ${s.parent.name}` : ''}`);
    }
    w.line('None,');
    w.close();
    w.line('');
    // User events, then one generated event per distinct timeout, then Completion if any completion
    // transition exists (see Machine.events); the generated ones are annotated.
    w.open('public enum Event');
    for (const e of m.events) {
        const timer = m.timers.find(x => x.event === e);
        const note = timer
            ? ` // after(${timer.milliseconds} ms) in ${timer.state.name}`
            : e === COMPLETION_EVENT && m.completion
              ? ' // internal: completion of a state'
              : stateflow && e === m.stepEvent
                ? ' // step: dispatch once per period'
                : '';
        w.line(`${e},${note}`);
    }
    w.close();
    w.line('');
    if (m.trace) {
        w.open('public enum TraceKind');
        w.line('Start,      // name = machine name');
        w.line('Event,      // name = event being dispatched');
        w.line('Ignored,    // name = event no state handled');
        w.line('Transition, // name = "Source -> Target"');
        w.line('Exit,       // name = state being exited');
        w.line('Enter,      // name = state being entered');
        w.close();
        w.line('');
    }
    w.line(`public const int StateCount = ${m.states.length};`);
    w.line(`public const int RegionCount = ${m.regions.length}; // region 0 is the top level`);
    if (m.queue) {
        w.line(`public const int QueueCapacity = ${m.queueCapacity};`);
    }
    w.line('');

    // ---- Fields ----
    if (table) {
        // One immutable row per transition. Optional columns (history, choice, trace name) only exist when
        // some transition needs them, so simple machines get a compact row type.
        const ctorParams = ['State source', 'Event trigger', 'Func<bool>? guard', 'Action? action', 'State target', 'State lca'];
        if (hasHistory) {
            ctorParams.push('bool history');
        }
        if (compound.length) {
            ctorParams.push('Func<bool>? fire');
        }
        if (temporal) {
            ctorParams.push('uint ticks');
        }
        // Choice rows have no trace name (their Fire_n method traces the branch taken), hence `string?`.
        if (m.trace) {
            ctorParams.push(compound.length ? 'string? name' : 'string name');
        }
        w.open('private sealed class TransitionRow');
        w.open(`public TransitionRow(${ctorParams.join(', ')})`);
        w.line('Source = source;');
        w.line('Trigger = trigger;');
        w.line('Guard = guard;');
        w.line('Action = action;');
        w.line('Target = target;');
        w.line('Lca = lca;');
        if (hasHistory) {
            w.line('History = history;');
        }
        if (compound.length) {
            w.line('Fire = fire;');
        }
        if (temporal) {
            w.line('Ticks = ticks;');
        }
        if (m.trace) {
            w.line('Name = name;');
        }
        w.close();
        w.line('');
        w.line('public State Source { get; }');
        w.line('public Event Trigger { get; }');
        w.line('public Func<bool>? Guard { get; }');
        w.line('public Action? Action { get; }');
        w.line('/// <summary>None for internal transitions.</summary>');
        w.line('public State Target { get; }');
        w.line('public State Lca { get; }');
        if (hasHistory) {
            w.line('/// <summary>Enter the target through its history.</summary>');
            w.line('public bool History { get; }');
        }
        if (compound.length) {
            w.line('/// <summary>Choice point: performs the whole transition.</summary>');
            w.line('public Func<bool>? Fire { get; }');
        }
        if (temporal) {
            w.line('/// <summary>after(): steps the source must have been active (0 = always).</summary>');
            w.line('public uint Ticks { get; }');
        }
        if (m.trace) {
            if (compound.length) {
                w.line('/// <summary>Null for choice rows.</summary>');
            }
            w.line(`public string${compound.length ? '?' : ''} Name { get; }`);
        }
        w.close();
        w.line('');
        // Static structure of the machine, indexed by `(int)state` (pre-order) or by region index. These
        // arrays replace the switch expressions of the switch style one for one.
        w.line(`private static readonly State[] Parents = { ${m.states.map(s => st(s.parent)).join(', ')} };`);
        w.line('// Region that contains each state, its first own region and its number of own regions.');
        w.line(`private static readonly int[] RegionOfState = { ${m.states.map(s => s.region.index).join(', ')} };`);
        // Simple states have no own region; 0 is a placeholder that is never used because their count is 0.
        w.line(`private static readonly int[] FirstRegions = { ${m.states.map(s => s.regions[0]?.index ?? 0).join(', ')} };`);
        w.line(`private static readonly int[] RegionCounts = { ${m.states.map(s => s.regions.length).join(', ')} };`);
        w.line(`private static readonly bool[] Finals = { ${m.states.map(s => (s.isFinal ? 'true' : 'false')).join(', ')} };`);
        // Region 0 (the top level) has no owner (State.None) and is never entered through EnterRegion (Start
        // enters the initial state itself); its entries only keep the arrays indexed by region number.
        w.line('// Owner and initial target of each region.');
        w.line(`private static readonly State[] RegionOwners = { ${m.regions.map(r => st(r.owner)).join(', ')} };`);
        w.line(`private static readonly State[] RegionTargets = { ${m.regions.map(r => st(r.initial!.target)).join(', ')} };`);
        if (hasHistory) {
            w.line('// 0 = none, 1 = shallow, 2 = deep');
            w.line(`private static readonly byte[] HistoryKinds = { ${m.states.map(s => (s.history === 'deep' ? '2' : s.history ? '1' : '0')).join(', ')} };`);
        }
        if (m.completion) {
            // completionOwner (cpp.ts): the state itself if it has completion transitions, else its parent
            // if the state is final and the parent has completion transitions, else None.
            w.line('// State whose completion transitions fire when this state is reached.');
            w.line(`private static readonly State[] CompletionOwners = { ${m.states.map(s => st(completionOwner(m, s))).join(', ')} };`);
        }
        if (hasTimers) {
            // Row i corresponds to MTimer.index i, the same index used by timerGenerations/timerArmed.
            w.line('// state, timeout event, milliseconds');
            w.line(
                `private static readonly (State State, Event Timeout, int Milliseconds)[] Timers = { ${m.timers.map(x => `(${st(x.state)}, ${ev(x.event)}, ${x.milliseconds})`).join(', ')} };`
            );
        }
        w.line('');
        // Instance arrays: the delegates are bound to `this`, so they are filled in by the constructor.
        w.line('private readonly Action?[] regionActions;');
        w.line('private readonly Action?[] entryActions;');
        w.line('private readonly Action?[] exitActions;');
        if (hasDuring) {
            w.line('private readonly Action?[] duringActions;');
        }
        w.line('private readonly TransitionRow[] transitions;');
    }
    // The active configuration: one slot per region. All slots are None until Start().
    w.line(`private readonly State[] active = { ${m.regions.map(() => 'State.None').join(', ')} }; // active state per region`);
    if (hasHistory) {
        // The state last exited from each region (None = none since Start), restored by history transitions.
        w.line(`private readonly State[] history = { ${m.regions.map(() => 'State.None').join(', ')} }; // state last exited per region`);
    }
    if (orthogonal) {
        // Outermost state exited by the latest transition of the current step (see DispatchState).
        w.line('private State exited = State.None;');
    }
    if (m.completion) {
        // Indexed by the owner state; set by MarkCompletion, consumed by RunCompletions.
        w.line('private readonly bool[] pending = new bool[StateCount]; // completion events not yet processed');
    }
    if (hasTimers) {
        // Per timer: a generation counter bumped on every start, and whether the timer is currently
        // running. Together they let DispatchTimeout discard late or superseded timeouts.
        w.line(`private readonly int[] timerGenerations = new int[${m.timers.length}];`);
        w.line(`private readonly bool[] timerArmed = new bool[${m.timers.length}];`);
    }
    if (temporal) {
        w.line('private readonly uint[] ticks = new uint[StateCount]; // steps since each state was entered (after())');
    }
    if (m.queue) {
        // Each entry is a closure that (re)sets the argument fields, if any, and dispatches its event.
        w.line('private readonly Queue<Func<bool>> queue = new Queue<Func<bool>>();');
    }
    if (hasArgs) {
        // The typed DispatchX/PostX methods store their arguments here; transition guards and actions
        // read them (callArgs). `default!` keeps #nullable enable quiet for reference-typed parameters.
        w.line('');
        w.line('// Arguments of the event being dispatched.');
        for (const e of paramEvents) {
            m.params.get(e)!.forEach(p => w.line(`private ${p.type} ${argField(e, p.name)} = default!;`));
        }
    }
    w.line('');

    // ---- Table-style constructor ----
    // Builds the delegate arrays and the transition table. Creating delegates to the abstract hooks here
    // is safe: they are only bound, not invoked, until Start() is called on the fully constructed object.
    if (table) {
        method(`protected ${cls}()`, () => {
            // Initial-transition actions per region (index 0, the top level, is never used: Start runs the
            // top-level initial actions itself), then entry and exit actions per state.
            w.line(`regionActions = new Action?[] { ${m.regions.map(r => (r.owner ? delegate(r.initial!.actions) : 'null')).join(', ')} };`);
            w.line(`entryActions = new Action?[] { ${m.states.map(s => delegate(s.entry)).join(', ')} };`);
            w.line(`exitActions = new Action?[] { ${m.states.map(s => delegate(s.exit)).join(', ')} };`);
            if (hasDuring) {
                w.line(`duringActions = new Action?[] { ${m.states.map(s => delegate(s.during)).join(', ')} };`);
            }
            const columns = ['source', 'event', 'guard', 'action', 'target', 'least common ancestor'];
            if (hasHistory) {
                columns.push('history');
            }
            if (compound.length) {
                columns.push('choice');
            }
            if (temporal) {
                columns.push('steps');
            }
            if (m.trace) {
                columns.push('trace name');
            }
            // A comment line naming the columns, so the table can be read without the row class.
            w.line(`// ${columns.join(', ')}`);
            w.line('transitions = new TransitionRow[]');
            w.line('{');
            w.indent();
            // Rows keep the model's order (by source state; transitions that may not fire before the one
            // that always fires), which HandleEvent relies on for priority.
            for (const t of m.transitions) {
                // A plain method group works only for a non-negated guard without parameters; anything
                // else needs a lambda (negation, or passing the stored event arguments).
                let guard = 'null';
                if (t.guard) {
                    guard = t.guard.negate || callArgs(t.event) ? `() => ${guardCall(t, t.event)}` : t.guard.name;
                }
                // Choice-point rows carry no action and no target: their Fire_n method runs the incoming
                // actions together with the chosen branch. Internal rows use State.None as the target,
                // which is how TryRow recognises them.
                const cells = [
                    st(t.source),
                    ev(t.event),
                    guard,
                    t.branches ? 'null' : delegate(t.actions, t.event),
                    t.internal || t.branches ? 'State.None' : st(t.target),
                    st(t.lca)
                ];
                if (hasHistory) {
                    cells.push(t.history ? 'true' : 'false');
                }
                if (compound.length) {
                    cells.push(t.branches ? fireName(t) : 'null');
                }
                if (temporal) {
                    cells.push(`${t.ticks ?? 0}u`);
                }
                // Choice rows have no trace name; Fire_n traces the chosen branch.
                if (m.trace) {
                    cells.push(t.branches ? 'null' : transitionName(t));
                }
                w.line(`new TransitionRow(${cells.join(', ')}),`);
            }
            w.dedent();
            w.line('};');
        });
    }

    /**
     * Emits `body` wrapped in Lock(); try { ... } finally { Unlock(); } when the threadSafe option is on,
     * so the lock is released even if a hook throws; emits `body` unwrapped otherwise.
     */
    const locked = (body: () => void) => {
        if (!m.threadSafe) {
            body();
            return;
        }
        w.line('Lock();');
        w.open('try');
        body();
        w.close();
        w.open('finally');
        w.line('Unlock();');
        w.close();
    };
    /**
     * Emits a read-only public property: expression-bodied normally, or with a block getter that takes the
     * lock when threadSafe is on.
     */
    const property = (decl: string, expr: string) => {
        if (m.threadSafe) {
            w.open(decl);
            w.open('get');
            locked(() => w.line(`return ${expr};`));
            w.close();
            w.close();
        } else {
            w.line(`${decl} => ${expr};`);
        }
        w.line('');
    };
    /**
     * Emits the tail of a public dispatch method: runs `dispatch` and returns its result. With the queue
     * option, events posted by hooks are drained first; the result reported is still that of the event
     * passed in, not of the queued ones.
     */
    const finishPublicDispatch = (dispatch: string) => {
        if (m.queue) {
            w.line(`var handled = ${dispatch};`);
            w.line('DrainQueue();');
            w.line('return handled;');
        } else {
            w.line(`return ${dispatch};`);
        }
    };

    // ---- Public interface ----
    // Current follows only the first region of orthogonal states (see Innermost); use IsIn to query the
    // other regions.
    w.line('/// <summary>Innermost active state (following the first region of orthogonal states).</summary>');
    property('public State Current', 'Innermost(active[0])');
    // A top-level final state is the only kind that finishes the machine; nested final states are
    // ordinary leaves (they may trigger their parent's completion transitions).
    w.line('/// <summary>True once a top-level final state has been reached.</summary>');
    property('public bool IsFinished', topFinals.length ? topFinals.map(s => `active[0] == ${st(s)}`).join(' || ') : 'false');

    // Start() is a full reset followed by the initial entry: every armed timer is cancelled (CancelTimer,
    // and a new generation so that a timeout still on its way is stale), the configuration, history, pending
    // completions and the queue are cleared; then the top-level initial transition's actions run and its
    // target is entered (which recursively follows initial transitions), and completions and queued events
    // are processed exactly as after a dispatched event. It is a reset, not a transition: states that were
    // active before are not exited, so their exit actions do not run.
    w.line('/// <summary>Resets the machine (running timers are cancelled, history is forgotten) and enters the initial state configuration.</summary>');
    method('public void Start()', () =>
        locked(() => {
            if (hasTimers) {
                const cancel = (i: string, e: string) => {
                    w.open(`if (timerArmed[${i}])`);
                    w.line(`timerArmed[${i}] = false;`);
                    w.line(`timerGenerations[${i}]++;`);
                    w.line(`CancelTimer(${e});`);
                    w.close();
                };
                if (table) {
                    w.open('for (var i = 0; i < Timers.Length; i++)');
                    cancel('i', 'Timers[i].Timeout');
                    w.close();
                } else {
                    m.timers.forEach(x => cancel(String(x.index), ev(x.event)));
                }
            }
            w.line('Array.Fill(active, State.None);');
            if (hasHistory) {
                w.line('Array.Fill(history, State.None);');
            }
            if (m.completion) {
                w.line('Array.Clear(pending, 0, pending.Length);');
            }
            if (m.queue) {
                w.line('queue.Clear();');
            }
            if (m.trace) {
                w.line(`Trace(TraceKind.Start, "${cls}");`);
            }
            m.initial.actions.forEach(a => w.line(`${a}();`));
            w.line(`${enterDown('State.None', st(m.initial.target), 'false')};`);
            if (m.completion) {
                w.line('RunCompletions();');
            }
            if (m.queue) {
                w.line('DrainQueue();');
            }
        })
    );

    // Untyped entry point for events without parameters.
    w.line('/// <summary>Dispatches an event to the innermost active states first. Returns false if the event was not handled.</summary>');
    if (rejected.length) {
        w.line('/// <remarks>Events with parameters must be sent with their typed Dispatch method; they are rejected here.</remarks>');
    }
    method('public bool Dispatch(Event trigger)', () =>
        locked(() => {
            if (rejected.length) {
                w.open(`if (${rejected.map(e => `trigger == ${ev(e)}`).join(' || ')})`);
                w.line('return false;');
                w.close();
            }
            finishPublicDispatch('DispatchCore(trigger)');
        })
    );
    // One typed DispatchX(...) per event with parameters: store the arguments in their fields (under the
    // lock), then dispatch as usual.
    for (const e of paramEvents) {
        const ps = m.params.get(e)!;
        method(`public bool Dispatch${e}(${ps.map(p => p.decl).join(', ')})`, () =>
            locked(() => {
                ps.forEach(p => w.line(`${argField(e, p.name)} = ${p.name};`));
                finishPublicDispatch(`DispatchCore(${ev(e)})`);
            })
        );
    }
    if (hasTimers) {
        // A timeout is honoured only if its timer is still armed (its state has not been exited since) and
        // the generation matches the latest StartTimer call (the state was not left and re-entered, which
        // would have restarted the timer). This makes timer callbacks that race with cancellation harmless.
        // Timers are one-shot: DispatchCore disarms the timer of a dispatched timeout, so a second call with
        // the same generation is ignored even if the timeout's guard was false or its transition internal.
        // Dispatch(timeout) is allowed too (to drive timeouts by hand): it skips the generation check but
        // disarms the timer just the same.
        w.line('/// <summary>Dispatches a timeout reported by a timer started with StartTimer; stale timeouts are ignored.</summary>');
        method('public bool DispatchTimeout(Event timeout, int generation)', () =>
            locked(() => {
                w.line('var index = TimerIndex(timeout);');
                w.open('if (index < 0 || !timerArmed[index] || timerGenerations[index] != generation)');
                w.line('return false;');
                w.close();
                finishPublicDispatch('DispatchCore(timeout)');
            })
        );
    }

    // Works for composite states too: an active composite occupies the slot of the region containing it.
    w.line('/// <summary>True if the given state is active.</summary>');
    method('public bool IsIn(State state)', () => locked(() => w.line('return state != State.None && active[RegionOf(state)] == state;')));

    // ParentOf is public and static (it depends only on the diagram); it is also the hierarchy walk used
    // by EnterDown, DispatchState and TryRow. The switch variant maps each child to its parent.
    if (table) {
        w.line('public static State ParentOf(State state) => state == State.None ? State.None : Parents[(int)state];');
        w.line('');
    } else {
        stateMap(
            'public static State ParentOf(State state)',
            m.states.filter(s => s.children.length > 0).map(p => [p.children, st(p)]),
            'State.None'
        );
    }

    // ---- Protected hooks for the derived class ----
    if (m.threadSafe) {
        w.line('/// <summary>Acquires mutual exclusion around every public member (e.g. Monitor.Enter on a private object).</summary>');
        w.line('/// <remarks>Hooks must not call public members of this class unless the lock is re-entrant.</remarks>');
        w.line('protected abstract void Lock();');
        w.line('/// <summary>Releases the lock acquired by <see cref="Lock"/>.</summary>');
        w.line('protected abstract void Unlock();');
    }
    if (hasTimers) {
        w.line('/// <summary>Starts a timer for an after(...) transition; when it elapses, call DispatchTimeout(timeout, generation).</summary>');
        w.line('protected abstract void StartTimer(Event timeout, int milliseconds, int generation);');
        w.line('/// <summary>Cancels a timer started by <see cref="StartTimer"/>.</summary>');
        w.line('protected abstract void CancelTimer(Event timeout);');
    }
    if (m.trace) {
        w.line('/// <summary>Override to log state machine activity.</summary>');
        w.open('protected virtual void Trace(TraceKind kind, string name)');
        w.close();
    }
    if (m.queue) {
        // Hooks must not call Dispatch re-entrantly (the machine is mid-transition); Post defers the event
        // until the current run-to-completion step has finished. Post does not lock: it is called from
        // hooks, which already hold the lock. The capacity check bounds the queue like the C++ ring buffer.
        w.line('/// <summary>Queues an event from inside a hook; it is processed after the current event. Returns false if the queue is full.</summary>');
        w.open('protected bool Post(Event trigger)');
        w.open(`if (${[...rejected.map(e => `trigger == ${ev(e)}`), 'queue.Count == QueueCapacity'].join(' || ')})`);
        w.line('return false;');
        w.close();
        w.line('queue.Enqueue(() => DispatchCore(trigger));');
        w.line('return true;');
        w.close();
        // Typed PostX: the closure captures the arguments and stores them in the fields only when it runs,
        // so arguments of several queued events do not overwrite each other.
        for (const e of paramEvents) {
            const ps = m.params.get(e)!;
            w.open(`protected bool Post${e}(${ps.map(p => p.decl).join(', ')})`);
            w.open('if (queue.Count == QueueCapacity)');
            w.line('return false;');
            w.close();
            w.open('queue.Enqueue(() =>');
            ps.forEach(p => w.line(`${argField(e, p.name)} = ${p.name};`));
            w.line(`return DispatchCore(${ev(e)});`);
            w.close('});');
            w.line('return true;');
            w.close();
        }
    }
    // The user's guard and action hooks; a hook used by transitions of an event with parameters receives
    // those parameters (the model ensures every use of a hook agrees on its parameter list).
    m.guards.forEach(g => w.line(`protected abstract bool ${g}(${paramDecls(g)});`));
    m.actions.forEach(a => w.line(`protected abstract void ${a}(${paramDecls(a)});`));
    w.line('');

    /**
     * Emits the entry half of a transition into `target` from below `lca`. A history transition targets
     * the composite owning the history pseudostate, and EnterDown restores its recorded configuration
     * (EnterHistory) instead of entering it by default.
     */
    const emitEnter = (lca: MState | null, target: MState, history: boolean) => {
        w.line(`${enterDown(st(lca), st(target), history ? 'true' : 'false')};`);
    };
    // Emits the statements that perform a (non-compound) transition and return true.
    // External transition, in UML order: trace, exit everything below the least common ancestor (the exit
    // root is the ancestor of the source that is a direct child of the LCA, resolved here at generation
    // time; ExitState exits the active states below it innermost first), run the transition's actions,
    // then enter from below the LCA down to the target. An internal transition only runs its actions. An
    // external self transition has the source's parent as LCA, so it exits and re-enters the source
    // (restarting its timers).
    const emitTransition = (t: MTransition) => {
        if (m.trace) {
            w.line(`Trace(TraceKind.Transition, ${transitionName(t)});`);
        }
        if (!t.internal) {
            w.line(`ExitState(${st(exitRoot(t.source, t.lca))});`);
        }
        t.actions.forEach(a => w.line(`${call(a, t.event)};`));
        if (!t.internal) {
            emitEnter(t.lca, t.target, t.history);
        }
        w.line('return true;');
    };
    /**
     * Emits the body of a choice-point transition (used inside the Fire_n methods).
     *
     * Junction semantics (manual, "Choice points"): all branch guards are evaluated before anything
     * happens, so a branch guard cannot observe the incoming actions. Branches are pre-sorted with guarded
     * ones first and the else/unguarded one last; each guarded branch becomes an `if` that performs the
     * whole transition and returns true, and the unguarded branch ends the sequence (any branches after it
     * would be unreachable). A branch that continues into another choice point recurses with the actions
     * collected so far. Only on a complete path are the source states exited, the actions of every segment
     * run in order (incoming transition first), and the branch's own target entered, using the branch's
     * own least common ancestor with the source.
     *
     * @param t The transition entering the (outermost) choice point; supplies the source and the event.
     * @param branches The branches of the choice point being emitted.
     * @param prefix Actions of the segments before this choice point, run before the branch's actions.
     */
    const emitBranches = (t: MTransition, branches: MBranch[], prefix: string[]) => {
        for (const b of branches) {
            if (b.guard) {
                w.open(`if (${guardCall(b, t.event)})`);
            }
            if (b.branches) {
                emitBranches(t, b.branches, [...prefix, ...b.actions]);
            } else {
                if (m.trace) {
                    w.line(`Trace(TraceKind.Transition, "${t.source.name} -> ${b.target!.name}${b.history ? ' (history)' : ''} (choice)");`);
                }
                w.line(`ExitState(${st(exitRoot(t.source, b.lca))});`);
                [...prefix, ...b.actions].forEach(a => w.line(`${call(a, t.event)};`));
                emitEnter(b.lca, b.target!, b.history);
                w.line('return true;');
            }
            if (b.guard) {
                w.close();
            } else {
                break;
            }
        }
    };

    // ---- Dispatch machinery ----
    // DispatchCore processes one event to completion: offer it to the active configuration from the top
    // (DispatchState recurses to the innermost states first), and if a transition fired, run the
    // completion transitions it triggered. Before Start() the configuration is empty and every event is
    // ignored. Queue draining is left to the public callers, so queued events never nest. A timeout event
    // disarms its timer first, whichever way it was dispatched (timers are one-shot), and with orthogonal
    // states `exited` is cleared for the step (see DispatchState).
    method('private bool DispatchCore(Event trigger)', () => {
        if (hasTimers) {
            w.line('var timer = TimerIndex(trigger);');
            w.open('if (timer >= 0)');
            w.line('timerArmed[timer] = false; // a timer fires once');
            w.close();
        }
        if (temporal) {
            w.open(`if (trigger == ${ev(m.stepEvent!)})`);
            w.line('CountSteps();');
            w.close();
        }
        if (orthogonal) {
            w.line('exited = State.None;');
        }
        if (m.trace) {
            w.line('Trace(TraceKind.Event, trigger.ToString());');
        }
        w.open('if (active[0] != State.None && DispatchState(active[0], trigger))');
        if (m.completion) {
            w.line('RunCompletions();');
        }
        w.line('return true;');
        w.close();
        if (m.trace) {
            w.line('Trace(TraceKind.Ignored, trigger.ToString());');
        }
        w.line('return false;');
    });
    // Inner states take priority: `state` only sees the event if none of its regions handled it. Every
    // active region is asked in order, so several orthogonal regions may react to the same event in one
    // step; but once a transition taken in one region has exited `state`, the remaining regions are not
    // asked, even when the transition entered `state` again (its fresh regions must not see the same event
    // twice). `exited`, the outermost state exited by the latest transition, tells: `state` was exited iff
    // `exited` is `state` or one of its ancestors. A transition that exits a state makes every DispatchState
    // level up to that state return at once, so when this is checked `exited` belongs to a transition taken
    // in the region just asked. Without orthogonal states there is at most one region and the first handled
    // event ends the loop.
    // Stateflow semantics reverse the order: `state`'s own transitions first; only if none fired, its during
    // actions run and the event is offered to the active state of every region (with the same `exited`
    // check for orthogonal states). During actions do not count as handling the event.
    if (stateflow) {
        w.line('// Stateflow semantics: offers the event to `state` itself first, then runs its during actions and');
        w.line('// offers it to every active region below `state`.');
        method('private bool DispatchState(State state, Event trigger)', () => {
            w.open('if (HandleEvent(state, trigger))');
            w.line('return true;');
            w.close();
            if (hasDuring) {
                w.line(table ? 'duringActions[(int)state]?.Invoke();' : 'OnDuring(state);');
            }
            if (orthogonal) {
                w.line('var handled = false;');
            }
            w.line('var first = FirstRegionOf(state);');
            w.open('for (var region = first; region < first + RegionsOf(state); region++)');
            w.open('if (active[region] != State.None && DispatchState(active[region], trigger))');
            if (orthogonal) {
                w.line('handled = true;');
                w.line('// Stop if the transition exited `state`, even if it entered it again.');
                w.open('for (var s = state; s != State.None; s = ParentOf(s))');
                w.open('if (s == exited)');
                w.line('return true;');
                w.close();
                w.close();
            } else {
                w.line('return true;');
            }
            w.close();
            w.close();
            w.line(orthogonal ? 'return handled;' : 'return false;');
        });
        if (temporal) {
            // CountSteps: a step event advances the counter of every active state before any transition is
            // tried; EnterState resets it, so a state entered during a step starts counting at the next one.
            w.line('// Advances the step counter of every active state (Stateflow after()).');
            method('private void CountSteps()', () => {
                w.open('for (var i = 0; i < StateCount; i++)');
                w.line('var state = (State)i;');
                w.open('if (active[RegionOf(state)] == state && ticks[i] != uint.MaxValue)');
                w.line('ticks[i]++;');
                w.close();
                w.close();
            });
        }
    } else {
        w.line('// Offers the event to every active region below `state` first, then to `state` itself.');
        method('private bool DispatchState(State state, Event trigger)', () => {
            if (orthogonal) {
                w.line('var handled = false;');
            }
            w.line('var first = FirstRegionOf(state);');
            w.open('for (var region = first; region < first + RegionsOf(state); region++)');
            w.open('if (active[region] != State.None && DispatchState(active[region], trigger))');
            if (orthogonal) {
                w.line('handled = true;');
                w.line('// Stop if the transition exited `state`, even if it entered it again.');
                w.open('for (var s = state; s != State.None; s = ParentOf(s))');
                w.open('if (s == exited)');
                w.line('return true;');
                w.close();
                w.close();
            } else {
                w.line('return true;');
            }
            w.close();
            w.close();
            w.line(orthogonal ? 'return handled || HandleEvent(state, trigger);' : 'return HandleEvent(state, trigger);');
        });
    }

    if (m.queue) {
        // FIFO; events posted while draining are appended and processed in the same loop. Each entry runs
        // DispatchCore, so its completions are processed before the next queued event.
        method('private void DrainQueue()', () => {
            w.open('while (queue.Count > 0)');
            w.line('queue.Dequeue()();');
            w.close();
        });
    }

    // One Fire_n per choice-point transition. Its incoming guard (if any) has already been checked by the
    // caller (HandleEvent in switch style, TryRow in table style). It returns false when no branch path is
    // enabled; the transition then counts as not enabled and the event continues to the next candidate.
    // For an exhaustive choice (one path is always taken) every path ends in `return true`, so no trailing
    // `return false` is emitted (it would be unreachable code).
    for (const t of compound) {
        w.line(`// ${t.kind === 'completion' ? 'Completion of' : `Event ${t.event} in`} ${t.source.name}: choice point.`);
        method(`private bool ${fireName(t)}()`, () => {
            emitBranches(t, t.branches!, t.actions);
            if (!isExhaustive(t.branches!)) {
                w.line('return false;');
            }
        });
    }

    if (m.completion) {
        // Run-to-completion of completion events. Entering a state may mark completions (MarkCompletion);
        // this loop processes them until none is left, always taking the lowest state index first, i.e.
        // outer states before inner ones in pre-order (the same order as the reference engine). A
        // completion is discarded if its state was exited in the meantime, or if no completion transition
        // is enabled (guards false). The event goes straight to HandleEvent of the completed state: it does
        // not bubble to ancestors. A completion transition may enter states that complete in turn. model.ts
        // rejects cycles of unguarded completion transitions; a guarded cycle runs for as long as its guards
        // stay true.
        w.line('// Completion transitions fire once a state is entered, or a composite state has reached final states in all regions.');
        method('private void RunCompletions()', () => {
            w.open('for (;;)');
            w.line('var index = Array.IndexOf(pending, true);');
            w.open('if (index < 0)');
            w.line('return;');
            w.close();
            w.line('pending[index] = false;');
            w.line('var state = (State)index;');
            w.open('if (active[RegionOf(state)] == state)');
            w.line(`HandleEvent(state, ${ev(COMPLETION_EVENT)});`);
            w.close();
            w.close();
        });
        // Called for every leaf state that has just been entered (see EnterDefault and EnterHistory). A simple state with
        // completion transitions completes immediately; a final state completes its parent if the parent
        // has completion transitions and, for an orthogonal parent, every region's active state is final.
        // Completion only propagates one level: a final state never completes its grandparent.
        method('private void MarkCompletion(State state)', () => {
            if (table) {
                // `owner == state` covers the leaf itself; AllRegionsFinal is also correct (and true) for a
                // single-region parent, whose only region has just reached the final state.
                w.line('var owner = CompletionOwners[(int)state];');
                w.open('if (owner != State.None && (owner == state || AllRegionsFinal(owner)))');
                w.line('pending[(int)owner] = true;');
                w.close();
            } else {
                // The switch variant resolves the owner per leaf at generation time (MarkCompletion is never
                // called for composites) and only emits the region check where it can fail, i.e. for
                // orthogonal parents.
                const cases: { labels: string[]; lines: string[] }[] = [];
                for (const s of m.states.filter(x => x.regions.length === 0)) {
                    const owner = completionOwner(m, s);
                    if (!owner) {
                        continue;
                    }
                    if (owner === s || owner.regions.length === 1) {
                        cases.push({ labels: [st(s)], lines: [`pending[${owner.index}] = true; // ${owner.name}`, 'break;'] });
                    } else {
                        cases.push({ labels: [st(s)], lines: [`if (AllRegionsFinal(${st(owner)}))`, `    pending[${owner.index}] = true; // ${owner.name}`, 'break;'] });
                    }
                }
                switchOn('state', cases);
            }
        });
        // Needed by the table variant unconditionally, and by the switch variant only for orthogonal
        // parents. An empty region (None) counts as not final, which IsFinalState handles.
        if (orthogonal || table) {
            method('private bool AllRegionsFinal(State state)', () => {
                w.line('var first = FirstRegionOf(state);');
                w.open('for (var region = first; region < first + RegionsOf(state); region++)');
                w.open('if (!IsFinalState(active[region]))');
                w.line('return false;');
                w.close();
                w.close();
                w.line('return true;');
            });
        }
    }

    if (hasTimers) {
        /**
         * Emits StartTimers/CancelTimers: a method that applies `lines` to every timer owned by the given
         * state. `lines` receives C# expressions for the timer index, its event and its duration, which are
         * loop variables in table style and literals in switch style.
         */
        const timerMethod = (name: string, lines: (i: string, event: string, ms: string) => string[]) => {
            method(`private void ${name}(State state)`, () => {
                if (table) {
                    w.open('for (var i = 0; i < Timers.Length; i++)');
                    w.open('if (Timers[i].State == state)');
                    lines('i', 'Timers[i].Timeout', 'Timers[i].Milliseconds').forEach(l => w.line(l));
                    w.close();
                    w.close();
                } else {
                    // One case per state that owns timers, listing all of its timers.
                    const owners = [...new Set(m.timers.map(x => x.state))];
                    switchOn(
                        'state',
                        owners.map(s => ({
                            labels: [st(s)],
                            lines: [...m.timers.filter(x => x.state === s).flatMap(x => lines(String(x.index), ev(x.event), String(x.milliseconds))), 'break;']
                        }))
                    );
                }
            });
        };
        // Starting a timer bumps its generation first, so any callback still pending from an earlier start
        // carries an old generation and is rejected by DispatchTimeout.
        timerMethod('StartTimers', (i, e, ms) => [`timerGenerations[${i}]++;`, `timerArmed[${i}] = true;`, `StartTimer(${e}, ${ms}, timerGenerations[${i}]);`]);
        // Disarm before asking the platform to cancel, so a callback that cannot be stopped any more is
        // ignored.
        timerMethod('CancelTimers', (i, e) => [`timerArmed[${i}] = false;`, `CancelTimer(${e});`]);
        // Maps a timeout event to its timer index, or -1 for any other event (DispatchTimeout rejects it).
        if (table) {
            w.line('private static int TimerIndex(Event timeout) => Array.FindIndex(Timers, timer => timer.Timeout == timeout);');
        } else {
            w.line('private static int TimerIndex(Event timeout) => timeout switch');
            w.line('{');
            w.indent();
            m.timers.forEach(x => w.line(`${ev(x.event)} => ${x.index},`));
            w.line('_ => -1,');
            w.dedent();
            w.line('};');
        }
        w.line('');
    }

    /**
     * Emits ExitState, which exits `state` and everything active below it. Order: exit the own regions last
     * to first (each recursively, innermost first), trace, cancel the state's timers (before its exit
     * actions), run its exit actions, and clear its region slot. With history pseudostates the state is then
     * recorded as the one last exited from its region, and with orthogonal states it becomes `exited`; the
     * exit root's call finishes last, so `exited` ends up holding the outermost exited state.
     *
     * @param exitCall Statement that runs the exit actions of `state` (style-specific).
     */
    const exitState = (exitCall: string) => {
        method('private void ExitState(State state)', () => {
            w.line('var first = FirstRegionOf(state);');
            w.open('for (var region = first + RegionsOf(state) - 1; region >= first; region--)');
            w.open('if (active[region] != State.None)');
            w.line('ExitState(active[region]);');
            w.close();
            w.close();
            if (m.trace) {
                w.line('Trace(TraceKind.Exit, state.ToString());');
            }
            if (hasTimers) {
                w.line('CancelTimers(state);');
            }
            w.line(exitCall);
            w.line('active[RegionOf(state)] = State.None;');
            if (hasHistory) {
                w.line('history[RegionOf(state)] = state;');
            }
            if (orthogonal) {
                w.line('exited = state;');
            }
        });
    };
    /**
     * Emits the entry side of the machinery: EnterDown, EnterState, EnterDefault, EnterHistory and Innermost.
     *
     * @param entryCall Statement that runs the entry actions of `state` (style-specific).
     * @param deepTest Expression telling whether the history pseudostate of `state` is deep (style-specific).
     */
    const enterFunctions = (entryCall: string, deepTest: string) => {
        // EnterDown(from, target[, history]) enters every state from below `from` (the LCA, or a region owner)
        // down to `target`, outermost first, then completes the entry of `target` by default (EnterDefault)
        // or, for a history transition, from its recorded history (EnterHistory). It works one level at a
        // time: walk up from `target` to the state just below `from` (`state`, and `next`, the one below it
        // on the path), enter `state`, and continue from there. With orthogonal states the regions of `state`
        // are entered in order: the region containing `next` along the path, the others by default.
        w.line('// Enters every state from below `from` down to `target`, then follows default (initial) transitions');
        w.line(hasHistory ? '// or, with `history`, restores the configuration recorded below `target`.' : '// below `target`.');
        method(`private void EnterDown(State from, State target${hasHistory ? ', bool history' : ''})`, () => {
            w.line('var state = target;');
            w.line('var next = State.None;');
            w.open('while (ParentOf(state) != from)');
            w.line('next = state;');
            w.line('state = ParentOf(state);');
            w.close();
            w.line('EnterState(state);');
            w.open('if (next == State.None)');
            if (hasHistory) {
                w.open('if (history)');
                w.line(`EnterHistory(state, ${deepTest});`);
                w.line('return;');
                w.close();
            }
            w.line('EnterDefault(state);');
            w.line('return;');
            w.close();
            if (orthogonal) {
                w.line('var first = FirstRegionOf(state);');
                w.open('for (var region = first; region < first + RegionsOf(state); region++)');
                w.open('if (region == RegionOf(next))');
                w.line(`${enterDown('state', 'target', 'history')};`);
                w.chain('else');
                w.line('EnterRegion(region);');
                w.close();
                w.close();
            } else {
                w.line(`${enterDown('state', 'target', 'history')};`);
            }
        });
        // Enters one state. It is marked active before its entry actions run (so IsIn is already true inside
        // them), and its timers start after.
        method('private void EnterState(State state)', () => {
            w.line('active[RegionOf(state)] = state;');
            if (temporal) {
                w.line('ticks[(int)state] = 0;');
            }
            if (m.trace) {
                w.line('Trace(TraceKind.Enter, state.ToString());');
            }
            w.line(entryCall);
            if (hasTimers) {
                w.line('StartTimers(state);');
            }
        });
        // Default entry: a composite enters each of its regions in order through the region's initial
        // transition. A leaf has been reached when there are no regions; that is where completions are
        // detected.
        method('private void EnterDefault(State state)', () => {
            w.line('var first = FirstRegionOf(state);');
            w.open('for (var region = first; region < first + RegionsOf(state); region++)');
            w.line('EnterRegion(region);');
            w.close();
            if (m.completion) {
                w.open('if (RegionsOf(state) == 0)');
                w.line('MarkCompletion(state);');
                w.close();
            }
        });
        // History entry: every region of `state` re-enters the state last exited from it, followed by that
        // state's default entry (shallow) or, recursively, by its own recorded regions (deep, which restores
        // every region of nested orthogonal states too). A region without a record (not exited since Start)
        // is entered by default; a leaf may complete, as in EnterDefault.
        if (hasHistory) {
            w.line('// Restores the regions of `state` from the states last exited from them (recursively for deep history).');
            method('private void EnterHistory(State state, bool deep)', () => {
                w.line('var first = FirstRegionOf(state);');
                w.open('for (var region = first; region < first + RegionsOf(state); region++)');
                w.line('var remembered = history[region];');
                w.open('if (remembered == State.None)');
                w.line('EnterRegion(region);');
                w.chain('else if (deep)');
                w.line('EnterState(remembered);');
                w.line('EnterHistory(remembered, true);');
                w.chain('else');
                w.line('EnterDown(state, remembered, false);');
                w.close();
                w.close();
                if (m.completion) {
                    w.open('if (RegionsOf(state) == 0)');
                    w.line('MarkCompletion(state);');
                    w.close();
                }
            });
        }
        // Follows the first region downwards; used by Current. Stops early at a composite whose region is
        // empty (only possible mid-transition).
        method('private State Innermost(State state)', () => {
            w.open('while (state != State.None && RegionsOf(state) > 0 && active[FirstRegionOf(state)] != State.None)');
            w.line('state = active[FirstRegionOf(state)];');
            w.close();
            w.line('return state;');
        });
    };

    // ---- Style-specific behaviour and structure ----
    if (table) {
        // Structure lookups backed by the static arrays. Callers never pass State.None to the first three
        // (it is not a valid index); IsFinalState receives region slots, which may be None.
        w.line('private static int RegionOf(State state) => RegionOfState[(int)state];');
        w.line('private static int FirstRegionOf(State state) => FirstRegions[(int)state];');
        w.line('private static int RegionsOf(State state) => RegionCounts[(int)state];');
        w.line('private static bool IsFinalState(State state) => state != State.None && Finals[(int)state];');
        w.line('');
        // Linear scan over the whole table; rows are in priority order, so the first enabled row of
        // `state` for `trigger` wins. A row whose guard is false (or whose choice point has no enabled
        // path) does not stop the scan.
        method('private bool HandleEvent(State state, Event trigger)', () => {
            w.open('foreach (var row in transitions)');
            w.open('if (row.Source == state && row.Trigger == trigger && TryRow(row))');
            w.line('return true;');
            w.close();
            w.close();
            w.line('return false;');
        });
        // Interprets one row; the run-time counterpart of emitTransition. The order of the checks matters:
        // choice rows also have Target == None, so they must be dispatched to their Fire_n method before
        // the internal-transition test.
        method('private bool TryRow(TransitionRow row)', () => {
            if (temporal) {
                w.open('if (row.Ticks != 0 && ticks[(int)row.Source] < row.Ticks)');
                w.line('return false;');
                w.close();
            }
            w.open('if (row.Guard != null && !row.Guard())');
            w.line('return false;');
            w.close();
            if (compound.length) {
                w.open('if (row.Fire != null)');
                w.line('return row.Fire();');
                w.close();
            }
            if (m.trace) {
                // Only choice rows have no name, and they returned above.
                w.line(`Trace(TraceKind.Transition, row.Name${compound.length ? '!' : ''});`);
            }
            if (hasInternal) {
                w.open('if (row.Target == State.None)');
                w.line('row.Action?.Invoke();');
                w.line('return true;');
                w.close();
            }
            // Exit root: the ancestor of the source (or the source itself) whose parent is the LCA; the
            // same as exitRoot() in cpp.ts, but computed at run time.
            w.line('var root = row.Source;');
            w.open('while (ParentOf(root) != row.Lca)');
            w.line('root = ParentOf(root);');
            w.close();
            w.line('ExitState(root);');
            w.line('row.Action?.Invoke();');
            // With history, EnterDown restores the target's recorded configuration (as in emitEnter).
            w.line(`${enterDown('row.Lca', 'row.Target', 'row.History')};`);
            w.line('return true;');
        });
        // Region initial transition: its actions run before its target (possibly nested deeper than a
        // direct child of the owner) is entered.
        method('private void EnterRegion(int region)', () => {
            w.line('regionActions[region]?.Invoke();');
            w.line(`${enterDown('RegionOwners[region]', 'RegionTargets[region]', 'false')};`);
        });
        exitState('exitActions[(int)state]?.Invoke();');
        // HistoryKinds tells EnterDown whether the history pseudostate of a history transition's target is deep.
        enterFunctions('entryActions[(int)state]?.Invoke();', 'HistoryKinds[(int)state] == 2');
    } else {
        // Nested switch: outer over the states that have outgoing transitions, inner over their events (in
        // Machine.events order). Within one (state, event) case, the transitions keep the model's priority
        // order: guarded ones become `if (guard) { ...; return true; }` and fall through to the next
        // candidate when false. Once a transition that always fires has been emitted, the remaining ones
        // are unreachable (the model reports more than one unguarded transition as an error), so emission
        // stops and no trailing `break;` is written, as the case already ends with a return.
        method('private bool HandleEvent(State state, Event trigger)', () => {
            const sources = m.states.filter(s => m.transitions.some(t => t.source === s));
            if (sources.length) {
                w.open('switch (state)');
                for (const s of sources) {
                    w.line(`case ${st(s)}:`);
                    w.indent();
                    w.open('switch (trigger)');
                    const own = m.transitions.filter(t => t.source === s);
                    for (const e of m.events.filter(e => own.some(t => t.event === e))) {
                        w.line(`case ${ev(e)}:`);
                        w.indent();
                        let fires = false;
                        for (const t of own.filter(t => t.event === e)) {
                            // The guard and, for temporal transitions, the step counter (tested first).
                            const cond = condition(t, e);
                            if (cond) {
                                w.open(`if (${cond})`);
                            }
                            if (t.branches) {
                                // An exhaustive, unguarded choice always returns true from Fire_n, so its
                                // result can be returned directly; otherwise a false result must let the
                                // next candidate transition be tried.
                                if (alwaysFires(t)) {
                                    w.line(`return ${fireName(t)}();`);
                                } else {
                                    w.open(`if (${fireName(t)}())`);
                                    w.line('return true;');
                                    w.close();
                                }
                            } else {
                                emitTransition(t);
                            }
                            if (cond) {
                                w.close();
                            }
                            if (alwaysFires(t)) {
                                fires = true;
                                break;
                            }
                        }
                        if (!fires) {
                            w.line('break;');
                        }
                        w.dedent();
                    }
                    w.close();
                    w.line('break;');
                    w.dedent();
                }
                w.close();
            }
            w.line('return false;');
        });

        // Structure lookups as switch expressions. Only non-default values get an arm: states of the top
        // region map to region 0 through the fallback, and simple states have no own regions (0, 0).
        const byRegion = new Map<number, MState[]>();
        m.states.forEach(s => byRegion.set(s.region.index, [...(byRegion.get(s.region.index) ?? []), s]));
        stateMap('private static int RegionOf(State state)', [...byRegion].filter(([r]) => r !== 0).map(([r, list]) => [list, String(r)]), '0');
        const composites = m.states.filter(s => s.regions.length > 0);
        stateMap('private static int FirstRegionOf(State state)', composites.map(s => [[s], String(s.regions[0].index)]), '0');
        stateMap('private static int RegionsOf(State state)', composites.map(s => [[s], String(s.regions.length)]), '0');
        // IsFinalState is only referenced by AllRegionsFinal, which the switch style needs only for
        // orthogonal parents with completion transitions.
        if (orthogonal && m.completion) {
            stateMap('private static bool IsFinalState(State state)', [[m.states.filter(s => s.isFinal), 'true']], 'false');
        }
        // One case per non-top region (the top-level initial transition is emitted inline in Start):
        // run the region's initial actions, then enter its initial target below the owner.
        method('private void EnterRegion(int region)', () =>
            switchOn(
                'region',
                m.regions
                    .filter(r => r.owner)
                    .map(r => ({
                        labels: [String(r.index)],
                        lines: [...r.initial!.actions.map(a => `${a}();`), `${enterDown(st(r.owner), st(r.initial!.target), 'false')};`, 'break;']
                    }))
            )
        );
        // Entry and exit actions per state; states without any have no case (the body may be empty).
        method('private void OnEntry(State state)', () =>
            switchOn('state', m.states.filter(s => s.entry.length).map(s => ({ labels: [st(s)], lines: [...s.entry.map(a => `${a}();`), 'break;'] })))
        );
        method('private void OnExit(State state)', () =>
            switchOn('state', m.states.filter(s => s.exit.length).map(s => ({ labels: [st(s)], lines: [...s.exit.map(a => `${a}();`), 'break;'] })))
        );
        if (hasDuring) {
            method('private void OnDuring(State state)', () =>
                switchOn('state', m.states.filter(s => s.during.length).map(s => ({ labels: [st(s)], lines: [...s.during.map(a => `${a}();`), 'break;'] })))
            );
        }
        // Whether the history pseudostate of a history transition's target is deep: a constant when all history
        // pseudostates are of one kind, otherwise IsDeepHistory, a switch expression over the deep ones.
        const deep = historyStates.filter(s => s.history === 'deep');
        if (deep.length > 0 && deep.length < historyStates.length) {
            stateMap('private static bool IsDeepHistory(State state)', [[deep, 'true']], 'false');
        }
        exitState('OnExit(state);');
        enterFunctions('OnEntry(state);', deep.length === 0 ? 'false' : deep.length === historyStates.length ? 'true' : 'IsDeepHistory(state)');
    }

    // Close the class and the namespace. Every member emitter appends a blank separator line; the one after
    // the last member is dropped so that the closing brace follows it directly.
    w.trimBlank();
    w.close();
    if (m.namespace) {
        w.close();
    }
    return w.toString();
}
